// Regenerates src/screenshot/roboto-metrics.js: advance widths, ink extents and kerning of the characters chat
// text uses, in Roboto 400 (messages) and 500 (names) from the app's own font files, measured by Chromium.
// Run: node scripts/electron.js scripts/update-roboto-metrics.js [--out=file]
// (--out writes somewhere else, e.g. to compare a new Electron's measurements with the committed ones.)
import { app, BrowserWindow, session } from 'electron';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { APP_ROOT, appUrl, handleAppScheme, registerAppScheme } from '../electron/protocol.js';

// Anything but --out=file is refused: `--out file`, ignored, would overwrite the committed metrics.
const args = process.argv.slice(2).filter((arg) => arg !== '--');
const wrong = args.find((arg) => !/^--out=./s.test(arg));
if (wrong !== undefined || args.length > 1) {
  console.error(`${wrong === undefined ? 'Give --out once' : `Unknown argument ${wrong}`}. Run: node scripts/electron.js scripts/update-roboto-metrics.js [--out=file]`);
  process.exit(2);
}
const out = args[0]?.slice('--out='.length);
const TARGET = path.resolve(out ?? path.join(APP_ROOT, 'src', 'screenshot', 'roboto-metrics.js'));

// A throwaway profile per run. Chromium keeps it locked until exit, so each run removes older runs' leftovers.
const PROFILE_PREFIX = 'youtube-comment-roboto-metrics-';
for (const entry of fs.readdirSync(os.tmpdir())) {
  if (!entry.startsWith(PROFILE_PREFIX)) continue;
  const dir = path.join(os.tmpdir(), entry);
  try {
    if (Date.now() - fs.statSync(dir).mtimeMs > 10 * 60 * 1000) fs.rmSync(dir, { recursive: true, force: true });
  } catch {
    // Still in use, or already gone.
  }
}
registerAppScheme();
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), PROFILE_PREFIX)));

// Printable ASCII, Latin-1, Latin Extended-A and the typographic punctuation phones put in chat.
const CODE_POINTS = [];
for (let c = 0x20; c <= 0x7e; c++) CODE_POINTS.push(c);
for (let c = 0xa1; c <= 0x17f; c++) if (c !== 0xad) CODE_POINTS.push(c);
CODE_POINTS.push(0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2122);

app.whenReady().then(async () => {
  const ses = session.fromPartition('roboto-metrics');
  handleAppScheme(ses);
  const win = new BrowserWindow({ show: false, webPreferences: { session: ses, sandbox: true, contextIsolation: true } });
  await win.loadURL(appUrl('src/stage/stage.html'));
  const metrics = await win.webContents.executeJavaScript(`(async () => {
    const SIZE = 1000;
    const codes = ${JSON.stringify(CODE_POINTS)};
    const text = String.fromCodePoint(...codes);
    await Promise.all(['400', '500'].map((w) => document.fonts.load(w + ' ' + SIZE + 'px Roboto', text)));
    const ctx = new OffscreenCanvas(1, 1).getContext('2d');
    const out = {};
    for (const weight of ['400', '500']) {
      ctx.font = weight + ' ' + SIZE + 'px Roboto';
      const glyphs = codes.map((c) => {
        const m = ctx.measureText(String.fromCodePoint(c));
        return [Math.round(m.width), Math.round(-m.actualBoundingBoxLeft), Math.round(m.actualBoundingBoxRight)];
      });
      // Kerning: how much a pair's width differs from its two advances (letters, digits and punctuation).
      const kerned = [];
      const ascii = codes.filter((c) => c > 0x20 && c < 0x7f);
      for (const a of ascii) {
        for (const b of ascii) {
          const pair = String.fromCodePoint(a, b);
          const kern = Math.round(ctx.measureText(pair).width - ctx.measureText(String.fromCodePoint(a)).width - ctx.measureText(String.fromCodePoint(b)).width);
          if (Math.abs(kern) >= 4) kerned.push(a.toString(16) + ',' + b.toString(16) + ':' + kern);
        }
      }
      out[weight] = { glyphs, kerned };
    }
    return out;
  })()`, true);
  // Per glyph: advance, ink left and ink right (from the pen position), all in thousandths of an em.
  const glyphs = (weight) => CODE_POINTS.map((c, i) => `${c.toString(16)}:${metrics[weight].glyphs[i].join(',')}`).join(' ');
  const source = `// Roboto 400 and 500 (the fonts in src/assets/fonts) as Chromium lays them out, in thousandths of an em, for
// the characters chat text mostly uses: per glyph "hex code point:advance,ink left,ink right" (ink measured
// from the pen position), and kerning as "first,second:adjustment". Generated by
// scripts/update-roboto-metrics.js; don't edit.
export const ROBOTO_GLYPHS = {
  400: '${glyphs('400')}',
  500: '${glyphs('500')}',
};

export const ROBOTO_KERNING = {
  400: '${metrics['400'].kerned.join(' ')}',
  500: '${metrics['500'].kerned.join(' ')}',
};
`;
  fs.writeFileSync(TARGET, source);
  console.log(`Wrote metrics for ${CODE_POINTS.length} characters and ${metrics['400'].kerned.length}/${metrics['500'].kerned.length} kerning pairs to ${path.relative(process.cwd(), TARGET)}`);
  app.exit(0);
}).catch((error) => {
  // Electron only warns about a rejection in the main process, and the hidden window would keep it running.
  console.error(error);
  app.exit(1);
});
